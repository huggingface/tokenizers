//! Writes the Python classes of the simple components into `src/components/generated/`.
//!
//! `tk-serialize` lists every simple component of `tokenizer.json` in [`tk::schemas`]: its
//! `"type"`, its doc and its fields. For each kind of component (normalizers, pre-tokenizers and
//! decoders), this tool writes one file with:
//!
//! 1. the imports,
//! 2. the kind's `Sequence` class,
//! 3. one class per component, with a constructor, and a getter and a setter per field,
//! 4. `from_json_type`, which picks the class of a component from its `"type"`,
//! 5. the kind's `#[pymodule]`.
//!
//! Then it writes the `mod.rs` that declares these files. Run it with `make components`.
//!
//! Each item is written with [`quote!`]: Rust code with `#name` holes that take a value from
//! the tool. [`prettyplease`] and `rustfmt` print it.

use std::error::Error;
use std::path::{Path, PathBuf};
use std::process::Command;

use proc_macro2::{Ident, Literal, TokenStream};
use quote::{format_ident, quote};
use tk::schemas::{
    ComponentSchema, DECODERS, FieldSchema, FieldType, FieldValue, KindSchema, NORMALIZERS,
    PRE_TOKENIZERS, SequenceSchema,
};

const HEADER: &str = "\
// Generated by tools/component-gen from tk-serialize's schemas. Do not edit by hand.
// Regenerate with `make components` in bindings/python.
";

fn main() -> Result<(), Box<dyn Error>> {
    let generated_dir = bindings_dir()?.join("src/components/generated");
    let kinds = [&NORMALIZERS, &PRE_TOKENIZERS, &DECODERS];

    let mut module_declarations = Vec::new();
    for kind in kinds {
        let path = generated_dir.join(format!("{}.rs", kind.module));
        write_rust_file(&path, kind_items(kind))?;

        let module = format_ident!("{}", kind.module);
        module_declarations.push(quote! { pub(crate) mod #module; });
    }
    write_rust_file(&generated_dir.join("mod.rs"), module_declarations)?;
    Ok(())
}

/// The directory of the extension crate, `bindings/python`.
fn bindings_dir() -> Result<PathBuf, Box<dyn Error>> {
    // `cargo run` sets the variable at run time. A compile-time `env!` would keep pointing at
    // wherever the checkout was when the tool was built.
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let bindings_dir = Path::new(&manifest_dir)
        .ancestors()
        .nth(2)
        .expect("the tool sits in bindings/python/tools/component-gen");
    Ok(bindings_dir.to_path_buf())
}

/// Prints `items` as the Rust file `path`, under the "generated" header.
fn write_rust_file(path: &Path, items: Vec<TokenStream>) -> Result<(), Box<dyn Error>> {
    let mut source = String::from(HEADER);
    // prettyplease puts no blank line between items, so each item is printed on its own.
    for item in items {
        let file: syn::File = syn::parse2(item)?;
        source.push('\n');
        source.push_str(&prettyplease::unparse(&file));
    }
    std::fs::write(path, layout_json_literals(&source))?;

    // prettyplease wraps at 80 columns. rustfmt wraps at the crate's 100, as `cargo fmt` does.
    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(path)
        .status()?;
    if !status.success() {
        return Err(format!("rustfmt failed on {}", path.display()).into());
    }
    println!("wrote {}", path.display());
    Ok(())
}

/// Lays out each `json!({...})` object literal in `source`: one key per line, or a single line for
/// an object with one key. prettyplease prints a macro's body as a run of tokens, and rustfmt
/// leaves it as it is.
fn layout_json_literals(source: &str) -> String {
    let mut laid_out = String::new();
    let mut rest = source;
    while let Some(start) = rest.find("json!(") {
        laid_out.push_str(&rest[..start]);
        let call = &rest[start..];
        // The keys are string literals and the values are arguments, so the first `)` closes the
        // call and no `,` or `:` hides inside a key or a value.
        let end = call
            .find(')')
            .expect("a json! call has a closing parenthesis");
        let body = call["json!(".len()..end].trim();
        rest = &call[end + 1..];

        // A setter's `json!(value)` is no object: it is laid out already.
        let Some(object) = body
            .strip_prefix('{')
            .and_then(|body| body.strip_suffix('}'))
        else {
            laid_out.push_str(&call[..=end]);
            continue;
        };
        let mut entries = Vec::new();
        for entry in object
            .split(',')
            .map(str::trim)
            .filter(|entry| !entry.is_empty())
        {
            let (key, value) = entry
                .split_once(':')
                .expect("a json! entry is `key: value`");
            entries.push(format!("{}: {}", key.trim(), value.trim()));
        }

        if let [entry] = entries.as_slice() {
            laid_out.push_str(&format!("json!({{{entry}}})"));
            continue;
        }
        let current_line = laid_out.rsplit('\n').next().unwrap_or_default();
        let indent = " ".repeat(current_line.len() - current_line.trim_start().len());
        laid_out.push_str("json!({\n");
        for entry in entries {
            laid_out.push_str(&format!("{indent}    {entry},\n"));
        }
        laid_out.push_str(&format!("{indent}}})"));
    }
    laid_out.push_str(rest);
    laid_out
}

/// The items of one kind's file, in file order.
fn kind_items(kind: &KindSchema) -> Vec<TokenStream> {
    let mut items = Vec::new();
    items.extend(imports(kind));
    if let Some(sequence) = &kind.sequence {
        items.extend(sequence_class(kind, sequence));
    }
    for component in kind.components {
        items.extend(component_class(kind, component));
    }
    items.push(from_json_type(kind));
    items.push(python_module(kind));
    items
}

/// The imports: the external crates first, then this crate.
fn imports(kind: &KindSchema) -> [TokenStream; 2] {
    let kind_class = format_ident!("{}", kind.kind);
    let module = format_ident!("{}", kind.module);
    // Every file gets the same imports, and a kind may not use them all. `quote!` drops comments,
    // so this one can't go in the generated file.
    let external = quote! {
        #![allow(unused_imports)]

        use std::sync::Arc;

        use base64::Engine as _;
        use base64::engine::general_purpose::STANDARD;
        use pyo3::exceptions::PyIndexError;
        use pyo3::prelude::*;
        use pyo3::types::PyBytes;
        use serde_json::json;
    };
    let internal = quote! {
        use crate::components::component_spec::{ComponentSpec, SequenceSpec};
        use crate::components::#module::#kind_class;
        use crate::components::{ComponentKind, JsonFieldsExt, check_choice};
        use crate::error::err;
        use crate::regex::Pattern;
    };
    [external, internal]
}

/// The kind's `Sequence` class: the struct, then its methods.
fn sequence_class(kind: &KindSchema, sequence: &SequenceSchema) -> [TokenStream; 2] {
    let kind_class = format_ident!("{}", kind.kind);
    let python_module = format!("tokenizers.{}", kind.module);
    let doc = doc_lines(sequence.doc);
    let items_key = sequence.items_key;

    let struct_item = quote! {
        #(#[doc = #doc])*
        #[pyclass(frozen, extends = #kind_class, module = #python_module)]
        pub struct Sequence;
    };
    let methods = quote! {
        #[pymethods]
        impl Sequence {
            #[new]
            #[pyo3(signature = (items, /))]
            fn new(items: Vec<Bound<'_, #kind_class>>) -> PyClassInitializer<Self> {
                let mut flat = Vec::with_capacity(items.len());
                for item in &items {
                    match #kind_class::spec(item) {
                        ComponentSpec::Single(single) => flat.push(single.clone()),
                        ComponentSpec::Sequence(sequence) => flat.extend(sequence.items()),
                    }
                }
                let sequence = SequenceSpec::new(#items_key, flat);
                #kind_class::initializer(ComponentSpec::Sequence(Arc::new(sequence)), Self)
            }

            fn __len__(slf: &Bound<'_, Self>) -> usize {
                #kind_class::sequence_spec(slf).len()
            }

            fn __getitem__(slf: &Bound<'_, Self>, index: isize) -> PyResult<Py<#kind_class>> {
                let spec = #kind_class::sequence_spec(slf);
                let item = spec.index(index).and_then(|index| spec.get(index));
                let item = item.ok_or_else(|| PyIndexError::new_err("Sequence index out of range"))?;
                #kind_class::from_spec(slf.py(), item)
            }

            fn __setitem__(
                slf: &Bound<'_, Self>,
                index: isize,
                item: Bound<'_, #kind_class>,
            ) -> PyResult<()> {
                let spec = #kind_class::sequence_spec(slf);
                let Some(item) = #kind_class::spec(&item).as_single() else {
                    return Err(err("a Sequence item can't be a Sequence"));
                };
                spec.index(index)
                    .and_then(|index| spec.set(index, item.clone()))
                    .ok_or_else(|| PyIndexError::new_err("Sequence assignment index out of range"))
            }
        }
    };
    [struct_item, methods]
}

/// One component's class: the struct, then its constructor, getters and setters.
fn component_class(kind: &KindSchema, component: &ComponentSchema) -> [TokenStream; 2] {
    let kind_class = format_ident!("{}", kind.kind);
    let python_module = format!("tokenizers.{}", kind.module);
    let class = rust_class_name(component.json_type);
    let json_type = component.json_type;
    let doc = doc_lines(component.doc);

    let mut signature = Vec::new();
    let mut arguments = Vec::new();
    let mut to_json = Vec::new();
    let mut keys = Vec::new();
    let mut names = Vec::new();
    let mut accessors = Vec::new();
    for field in component.fields {
        let key = field.key;
        let name = format_ident!("{key}");
        let conversion = field_conversion(field);
        let argument_type = &conversion.argument_type;

        signature.push(signature_argument(field));
        arguments.push(quote! { #name: #argument_type });
        to_json.push(conversion.to_json.clone());
        keys.push(key);
        names.push(name);
        accessors.push(field_accessors(field, &conversion));
    }
    // pyo3 needs a signature only to give an argument a default.
    let signature =
        (!signature.is_empty()).then(|| quote! { #[pyo3(signature = (#(#signature),*))] });

    let struct_item = quote! {
        #(#[doc = #doc])*
        #[pyclass(frozen, extends = #kind_class, name = #json_type, module = #python_module)]
        pub struct #class;
    };
    let methods = quote! {
        #[pymethods]
        impl #class {
            #[new]
            #signature
            fn new(#(#arguments),*) -> PyResult<PyClassInitializer<Self>> {
                #(#to_json)*
                let spec = ComponentSpec::from_literal(json!({"type": #json_type, #(#keys: #names),*}));
                Ok(#kind_class::initializer(spec, Self))
            }

            #(#accessors)*
        }
    };
    [struct_item, methods]
}

/// The getter and the setter of one field.
fn field_accessors(field: &FieldSchema, conversion: &FieldConversion) -> TokenStream {
    let key = field.key;
    let getter = format_ident!("{key}");
    let setter = format_ident!("set_{key}");
    let FieldConversion {
        argument_type,
        to_json,
        getter_type,
        getter_body,
    } = conversion;
    let getter_body = getter_body
        .clone()
        .unwrap_or_else(|| quote! { slf.field(#key) });
    quote! {
        #[getter]
        fn #getter<'py>(slf: &Bound<'py, Self>) -> PyResult<#getter_type> {
            #getter_body
        }

        #[setter]
        fn #setter(slf: &Bound<'_, Self>, #getter: #argument_type) -> PyResult<()> {
            #to_json
            slf.set_field(#key, json!(#getter));
            Ok(())
        }
    }
}

/// How a field's value moves between Python and the component's JSON.
struct FieldConversion {
    /// The type the constructor and the setter take from Python.
    argument_type: TokenStream,
    /// Statements run on the argument before it goes into the JSON. They check it, or rebind it
    /// to the value the JSON holds.
    to_json: TokenStream,
    /// The type the getter returns to Python.
    getter_type: TokenStream,
    /// The getter's body, when it does more than return the value as the JSON holds it.
    getter_body: Option<TokenStream>,
}

fn field_conversion(field: &FieldSchema) -> FieldConversion {
    let key = field.key;
    let name = format_ident!("{key}");
    // Most types go into the JSON and come back out as they are.
    let unchanged = |rust_type: TokenStream| FieldConversion {
        argument_type: rust_type.clone(),
        to_json: quote! {},
        getter_type: rust_type,
        getter_body: None,
    };
    match field.field_type {
        FieldType::Bool => unchanged(quote! { bool }),
        FieldType::Char => unchanged(quote! { char }),
        FieldType::Usize => unchanged(quote! { usize }),
        FieldType::OptionalBool => unchanged(quote! { Option<bool> }),
        FieldType::Pattern => unchanged(quote! { Pattern }),
        FieldType::String => FieldConversion {
            argument_type: quote! { &str },
            ..unchanged(quote! { String })
        },
        FieldType::Choice(choices) => FieldConversion {
            argument_type: quote! { &str },
            to_json: quote! { check_choice(#key, #name, &[#(#choices),*])?; },
            ..unchanged(quote! { String })
        },
        FieldType::Base64Bytes => FieldConversion {
            argument_type: quote! { &[u8] },
            to_json: quote! { let #name = STANDARD.encode(#name); },
            getter_type: quote! { Bound<'py, PyBytes> },
            getter_body: Some(quote! {
                let encoded: String = slf.field(#key)?;
                let bytes = STANDARD.decode(encoded).map_err(err)?;
                Ok(PyBytes::new(slf.py(), &bytes))
            }),
        },
    }
}

/// One argument of the constructor's `#[pyo3(signature = ...)]`, with its default if it has one.
fn signature_argument(field: &FieldSchema) -> TokenStream {
    let name = format_ident!("{}", field.key);
    match &field.default {
        None => quote! { #name },
        Some(FieldValue::Bool(value)) => quote! { #name = #value },
        Some(FieldValue::Str(value)) => quote! { #name = #value },
        Some(FieldValue::Char(value)) => quote! { #name = #value },
        Some(FieldValue::Usize(value)) => {
            // `quote!` would write `5usize`, which pyo3 does not turn into a Python default.
            let value = Literal::usize_unsuffixed(*value);
            quote! { #name = #value }
        }
        Some(FieldValue::Null) => quote! { #name = None },
    }
}

/// `from_json_type`, which builds a handle of the class a `"type"` names. Any other `"type"`
/// gets a handle of the plain kind.
fn from_json_type(kind: &KindSchema) -> TokenStream {
    let kind_class = format_ident!("{}", kind.kind);
    let mut arms = Vec::new();
    for component in kind.components {
        let json_type = component.json_type;
        let class = rust_class_name(json_type);
        arms.push(
            quote! { Some(#json_type) => #kind_class::concrete_component(py, spec, #class), },
        );
    }
    quote! {
        #[doc = " Builds a handle of the class `json_type` names, or a plain kind handle for another type."]
        pub(crate) fn from_json_type(
            py: Python<'_>,
            spec: ComponentSpec,
            json_type: Option<&str>,
        ) -> PyResult<Py<#kind_class>> {
            match json_type {
                #(#arms)*
                _ => #kind_class::default_component(py, spec),
            }
        }
    }
}

/// The kind's `#[pymodule]`, exporting the kind, its `Sequence` and every component class.
fn python_module(kind: &KindSchema) -> TokenStream {
    let module = format_ident!("{}", kind.module);
    let mut classes = vec![format_ident!("{}", kind.kind)];
    if kind.sequence.is_some() {
        classes.push(format_ident!("Sequence"));
    }
    for component in kind.components {
        classes.push(rust_class_name(component.json_type));
    }
    quote! {
        #[pymodule]
        pub mod #module {
            #[pymodule_export]
            use super::{#(#classes),*};
        }
    }
}

/// The Rust name of a component's class. An all-capitals `"type"` such as `NFC` becomes `Nfc`,
/// as Rust spells acronyms. The Python name stays the `"type"`.
fn rust_class_name(json_type: &str) -> Ident {
    if json_type.chars().all(|c| c.is_ascii_uppercase()) {
        let (first, rest) = json_type.split_at(1);
        format_ident!("{first}{}", rest.to_ascii_lowercase())
    } else {
        format_ident!("{json_type}")
    }
}

/// `doc` as the lines of a `///` comment, at most 96 columns wide. Each line starts with the
/// space that follows `///`.
fn doc_lines(doc: &str) -> Vec<String> {
    let mut lines = Vec::new();
    let mut line = String::new();
    for word in doc.split_whitespace() {
        if !line.is_empty() && line.len() + 1 + word.len() > 92 {
            lines.push(std::mem::take(&mut line));
        }
        line.push(' ');
        line.push_str(word);
    }
    lines.push(line);
    lines
}
