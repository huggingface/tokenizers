use crate::classify::{Atom, in_mask};




#[inline]
pub(crate) fn run_end(tags: &[u8], mut i: usize, end: usize, m: u16) -> usize {
    let m = m | Atom::Cont.bit();
    while i < end && in_mask(tags[i], m) {
        i += 1;
    }
    i
}




