//! `bitsplit` — GPT-family pre-tokenization as a **bitstream program**, replacing the scalar FSMs.
//!
//! Follows *Interleaved Bitstream Execution for Multi-Pattern Regex Matching on GPUs*
//! (MICRO'25, doi 10.1145/3725843.3756052). The paper's two ideas that carry over to a CPU:
//!
//!   1. **Bit-parallel regex.** Compile the grammar into character-class *bitstreams* (one bit per
//!      input byte) plus boolean ops and carry-propagating adds. 64 input bytes are decided per
//!      64-bit register op, branchlessly — the FSM's per-token unpredictable branch disappears.
//!   2. **Interleaved execution.** Do NOT run one loop per bitstream instruction over the whole
//!      input (that is the "sequential" baseline the paper beats: every intermediate stream is
//!      materialised and re-read). Instead fuse *all* instructions into ONE block-wise loop, so an
//!      intermediate stream lives in a register for the ~100 ops it is needed and dies there. The
//!      only thing that reaches memory is the final `starts` bitmap (n/8 bytes).
//!
//! The paper's third contribution (dependency-aware thread-data mapping) is a GPU concern — it
//! resolves cross-block dependencies by recomputing them on other SMs. On one core the blocks are
//! visited in order, so those dependencies are carried in a handful of scalar registers and, for
//! the one genuinely backward-in-time rule, patched into the already-written bitmap.
//!
//! We do not re-derive character classes: [`classify`] already emits one `Atom` tag per byte. The
//! builder folds those 16 atoms into a grammar-specific **dense 3-bit code** and extracts 3
//! bit-planes of it; every class stream is then a 2–3 op boolean function of the planes.
//!
//! Grammars: [`bitsplit_deepseek`], [`bitsplit_byte_level`] (GPT-2), [`bitsplit_cl100k`]. All three
//! byte-exact with the oniguruma oracle over a block-phase sweep — see `tests/parity.rs`.

/// Declares a grammar's block-local class streams, and with them the two carried shifts every
/// rule needs: `back` — what held one position earlier, carrying in the previous block's last
/// bit — and `fwd`, one position later, carrying in the next block's first bit.
///
/// This is the whole cross-block story. Keeping the carry in the *stream* instead of passing it at
/// every call site is what lets a rule read as plain stream algebra: "a run starts where this class
/// holds and the position before it did not" is `x & lead & !bk.x`, exact at a block edge. Before
/// this, each grammar rebuilt the edge byte's class into a `u16` mask (`code_bits`/`bits_at`) and
/// threaded it through every shift by hand — so the boundary byte got classified twice, once by the
/// builder and again scalar-side.
macro_rules! streams {
    ($(#[$m:meta])* $name:ident { $($f:ident),+ $(,)? }) => {
        $(#[$m])*
        #[derive(Clone, Copy, Default)]
        pub(crate) struct $name { $(pub(crate) $f: u64,)+ }

        impl $name {
            /// Every stream shifted one position later, carrying in `p`'s last bit.
            #[inline]
            pub(crate) fn back(&self, p: &Self) -> Self {
                Self { $($f: (self.$f << 1) | (p.$f >> 63),)+ }
            }

            /// Every stream shifted one position earlier, carrying in `n`'s first bit.
            #[inline]
            pub(crate) fn fwd(&self, n: &Self) -> Self {
                Self { $($f: (self.$f >> 1) | (n.$f << 63),)+ }
            }
        }

        impl crate::Streams for $name {
            #[inline]
            fn back(&self, p: &Self) -> Self { $name::back(self, p) }
            #[inline]
            fn fwd(&self, n: &Self) -> Self { $name::fwd(self, n) }
            #[inline]
            fn lead(&self) -> u64 { self.lead }
        }
    };
}

/// A grammar's class-stream set, as generated by [`streams!`]. Every grammar declares `lead` and
/// `cont`, because the driver needs them for the char-boundary geometry.
pub(crate) trait Streams: Copy + Default {
    fn back(&self, p: &Self) -> Self;
    fn fwd(&self, n: &Self) -> Self;
    fn lead(&self) -> u64;
}

/// Everything a rule needs about one block, prepared once by [`blocks`] instead of re-derived by
/// every grammar: the previous / current / next blocks, both carried shifts, and the geometry.
pub(crate) struct Ctx<C> {
    /// the previous block's streams (all-zero before the first)
    pub pv: C,
    pub cur: C,
    /// the next block's streams (all-zero past the last)
    pub nx: C,
    /// `cur` one position later, carrying in `pv`'s last bit — "what held just before here"
    pub bk: C,
    /// `cur` one position earlier, carrying in `nx`'s first bit — "what holds just after here"
    pub fw: C,
    pub bi: usize,
    pub base: usize,
    pub len: usize,
    /// bits inside this block (`!0` for a full one)
    pub valid: u64,
    pub last_blk: bool,
    /// this position is the LAST byte of its char (the input's final byte counts)
    pub lb: u64,
    /// the input's final byte as a bit, else 0
    pub eof: u64,
}

/// What a rule returns for its block: the token-start bitmap, and a patch OR-ed into the
/// *previous* block (a char straddling the edge lands its lead in the word already written).
///
/// A grammar with a scalar escape owns its `flag` bitmap directly — o200k's escape gate patches
/// `flag[bi - 1]` and arbitrary earlier words, which no single mask can express.
pub(crate) struct Out {
    pub st: u64,
    pub patch: u64,
}

/// Drive a grammar block by block with one block of lookahead.
///
/// This owns everything that is *not* grammar — block geometry, the fill-seed threading (inside
/// `build`'s captures), the previous/current/next rotation, both carried shifts, `lb`, the eof bit,
/// and the starts/flag assembly. A grammar supplies its atom table, its plane decode, and its
/// rules; nothing else. `rule` also gets `starts` because one rule (deepseek's `anl`) retracts a
/// start it committed in an earlier block.
#[inline]
pub(crate) fn blocks<C, B, R>(ntext: usize, starts: &mut [u64], mut build: B, mut rule: R)
where
    C: Streams,
    B: FnMut(usize, usize) -> C,
    R: FnMut(&Ctx<C>, &mut [u64]) -> Out,
{
    let nblk = ntext.div_ceil(64);
    let blen = |bi: usize| (ntext - bi * 64).min(64);
    let mut pv = C::default();
    let mut cur = build(0, blen(0));

    for bi in 0..nblk {
        let base = bi * 64;
        let len = blen(bi);
        let last_blk = base + len == ntext;
        // built BEFORE this block is processed, which is what makes `fw` a real carry
        let nx = if last_blk {
            C::default()
        } else {
            build(base + 64, blen(bi + 1))
        };
        let valid = if len == 64 { !0u64 } else { (1u64 << len) - 1 };
        let eof = if last_blk { 1u64 << (len - 1) } else { 0 };
        let bk = cur.back(&pv);
        let fw = cur.fwd(&nx);
        let ctx = Ctx {
            pv,
            cur,
            nx,
            bk,
            fw,
            bi,
            base,
            len,
            valid,
            last_blk,
            lb: (fw.lead() & valid) | eof,
            eof,
        };
        let o = rule(&ctx, starts);
        let mut st = o.st & cur.lead();
        if bi == 0 {
            st |= 1; // position 0 always opens a token
        }
        starts[bi] = st;
        if bi > 0 {
            starts[bi - 1] |= o.patch;
        }
        pv = cur;
        cur = nx;
    }
}

