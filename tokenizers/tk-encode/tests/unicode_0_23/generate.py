"""Regenerate blocks.txt from the released 0.23 wheel.

    uv run --no-project --with 'tokenizers==0.23.2' python tk-encode/tests/unicode_0_23/generate.py

Every code point goes through `Lowercase` and through `Digits` in both modes. A block of 256 code
points is listed, with an FNV-1a hash of its outputs, when one of them changes its input. main.rs
hashes the same bytes.
"""

import re
import sys
from pathlib import Path

import tokenizers
from tokenizers import normalizers, pre_tokenizers

BLOCK = 256
FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
# Never in UTF-8, so they cannot be confused with an output byte.
PIECE_END = b"\xfe"
OUTPUT_END = b"\xff"


LOWERCASE = normalizers.Lowercase()


def lowercase(c):
    out = LOWERCASE.normalize_str(c)
    return out.encode() + OUTPUT_END, out == c


def digits(individual_digits):
    pre_tokenizer = pre_tokenizers.Digits(individual_digits=individual_digits)

    def run(c):
        # Two in a row so a numeric code point splits in both modes.
        text = f"a{c}{c}a"
        pieces = [piece for piece, _ in pre_tokenizer.pre_tokenize_str(text)]
        output = b"".join(piece.encode() + PIECE_END for piece in pieces)
        return output + OUTPUT_END, pieces == [text]

    return run


COMPONENTS = {
    "lowercase": lowercase,
    "digits": digits(False),
    "digits_individual": digits(True),
}


def built_with():
    binary = Path(tokenizers.tokenizers.__file__).read_bytes()
    found = re.search(rb"rustc version [0-9.]+ \([0-9a-f]+ [0-9-]+\)", binary)
    if found is None:
        found = re.search(rb"/rustc/[0-9a-f]{40}", binary)
    return found.group().decode() if found else "an unknown rustc"


def main():
    if not tokenizers.__version__.startswith("0.23."):
        sys.exit(f"needs a 0.23 wheel, found tokenizers {tokenizers.__version__}")
    bert = normalizers.BertNormalizer(
        clean_text=False,
        handle_chinese_chars=False,
        strip_accents=False,
        lowercase=True,
    )
    wheel = f"the tokenizers {tokenizers.__version__} wheel, built with {built_with()}"
    lines = [
        f"# Generated by generate.py from {wheel}.",
        "# <component> <first code point of the block> <FNV-1a of its outputs>",
    ]
    for name, run in COMPONENTS.items():
        for start in range(0, 0x110000, BLOCK):
            digest, changed = FNV_OFFSET, False
            for cp in range(start, start + BLOCK):
                if 0xD800 <= cp <= 0xDFFF:
                    continue
                c = chr(cp)
                output, unchanged = run(c)
                changed |= not unchanged
                # main.rs checks BertNormalizer's lowercasing against these lines too.
                if name == "lowercase":
                    assert bert.normalize_str(c) == LOWERCASE.normalize_str(c), hex(cp)
                for byte in output:
                    digest = ((digest ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
            if changed:
                lines.append(f"{name} {start:04X} {digest:016x}")
    out = Path(__file__).with_name("blocks.txt")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
